/// Arkworks' prepared G2 point (the line-coefficient vector).
pub type ArkG2Prepared = <Bn254 as Pairing>::G2Prepared;

/// u32 words per line coefficient (3 Fq2).
pub const ELL_COEFF_U32S: usize = 6 * FR_U32_LIMBS;

/// u32 words per Fq12 (device order = arkworks memory order).
pub const FQ12_U32S: usize = 12 * FR_U32_LIMBS;

/// Line coefficients per prepared pair: one per ate iteration, one more per
/// nonzero ate digit, two Frobenius addition steps.
pub fn ell_coeffs_per_pair() -> usize {
    let ate = <ark_bn254::Config as ark_ec::bn::BnConfig>::ATE_LOOP_COUNT;
    let nonzero = ate[..ate.len() - 1].iter().filter(|&&d| d != 0).count();
    (ate.len() - 1) + nonzero + 2
}

fn fq_mont_limbs(x: Fq) -> [u32; FR_U32_LIMBS] {
    let mut out = [0u32; FR_U32_LIMBS];
    for (i, w) in x.0 .0.iter().enumerate() {
        out[2 * i] = *w as u32;
        out[2 * i + 1] = (*w >> 32) as u32;
    }
    out
}

fn fq_from_mont_limbs(limbs: &[u32]) -> Fq {
    let mut words = [0u64; 4];
    for (i, w) in words.iter_mut().enumerate() {
        *w = u64::from(limbs[2 * i]) | (u64::from(limbs[2 * i + 1]) << 32);
    }
    Fq::new_unchecked(BigInt::new(words))
}

fn fq2_from_mont_limbs(limbs: &[u32]) -> Fq2 {
    Fq2::new(
        fq_from_mont_limbs(&limbs[..FR_U32_LIMBS]),
        fq_from_mont_limbs(&limbs[FR_U32_LIMBS..]),
    )
}

fn write_fq2(dst: &mut [u32], x: &Fq2) {
    dst[..FR_U32_LIMBS].copy_from_slice(&fq_mont_limbs(x.c0));
    dst[FR_U32_LIMBS..2 * FR_U32_LIMBS].copy_from_slice(&fq_mont_limbs(x.c1));
}

/// Rebuild one device Fq6 (6 Montgomery Fq limb runs, arkworks order).
pub fn fq6_from_device_limbs(limbs: &[u32]) -> Fq6 {
    debug_assert_eq!(limbs.len(), 6 * FR_U32_LIMBS);
    Fq6::new(
        fq2_from_mont_limbs(&limbs[..2 * FR_U32_LIMBS]),
        fq2_from_mont_limbs(&limbs[2 * FR_U32_LIMBS..4 * FR_U32_LIMBS]),
        fq2_from_mont_limbs(&limbs[4 * FR_U32_LIMBS..]),
    )
}

/// An Fq6's device words.
pub fn fq6_to_device_limbs(x: &Fq6) -> [u32; 6 * FR_U32_LIMBS] {
    let mut out = [0u32; 6 * FR_U32_LIMBS];
    for (i, c2) in [&x.c0, &x.c1, &x.c2].into_iter().enumerate() {
        write_fq2(
            &mut out[i * 2 * FR_U32_LIMBS..(i + 1) * 2 * FR_U32_LIMBS],
            c2,
        );
    }
    out
}

/// Rebuild one device Fq12 (12 Montgomery Fq limb runs, arkworks order).
pub fn fq12_from_device_limbs(limbs: &[u32]) -> Fq12 {
    debug_assert_eq!(limbs.len(), FQ12_U32S);
    Fq12::new(
        fq6_from_device_limbs(&limbs[..6 * FR_U32_LIMBS]),
        fq6_from_device_limbs(&limbs[6 * FR_U32_LIMBS..]),
    )
}

/// An Fq12's device words (test/bench input construction).
pub fn fq12_to_device_limbs(x: &Fq12) -> [u32; FQ12_U32S] {
    let mut out = [0u32; FQ12_U32S];
    for (i, c2) in [&x.c0.c0, &x.c0.c1, &x.c0.c2, &x.c1.c0, &x.c1.c1, &x.c1.c2]
        .into_iter()
        .enumerate()
    {
        write_fq2(
            &mut out[i * 2 * FR_U32_LIMBS..(i + 1) * 2 * FR_U32_LIMBS],
            c2,
        );
    }
    out
}

fn limb_array(limbs: &[u32]) -> String {
    let body: Vec<String> = limbs.iter().map(|l| format!("{l:#010x}u")).collect();
    format!("{{ {} }}", body.join(", "))
}

/// Pairing constants for the MSL preamble, read from arkworks' BN254
/// configuration. Asserts the structural facts the shaders bake in —
/// tower shape (ξ = 9 + u over u² = −1), positive x, and the coefficient
/// count against an actual arkworks preparation — so a config drift fails
/// at context construction, never as wrong arithmetic.
#[expect(
    clippy::expect_used,
    reason = "structural invariants of BN254 itself; violated only if the arkworks dep changes curves"
)]
pub(super) fn pairing_preamble() -> String {
    use std::fmt::Write as _;
    type Config = ark_bn254::Config;

    assert_eq!(
        <ark_bn254::Fq6Config as Fp6Config>::NONRESIDUE,
        Fq2::new(Fq::from(9u64), Fq::one()),
        "fq12.metal specializes ξ = 9 + u",
    );
    assert_eq!(
        <ark_bn254::Fq2Config as ark_ff::Fp2Config>::NONRESIDUE,
        -Fq::one(),
        "g2.metal's Fq2 arithmetic assumes u² = −1",
    );
    // The Miller kernels skip the negative-x conjugations.
    const _: () = assert!(!<ark_bn254::Config as ark_ec::bn::BnConfig>::X_IS_NEGATIVE);

    let ate = <Config as ark_ec::bn::BnConfig>::ATE_LOOP_COUNT;
    let coeffs = ell_coeffs_per_pair();
    let reference: ArkG2Prepared = G2Affine::generator().into();
    assert_eq!(
        reference.ell_coeffs.len(),
        coeffs,
        "emitted coefficient count must match arkworks' preparation",
    );

    let two_inv = Fq::from(2u64).inverse().expect("2 is invertible in Fq");
    let g2b = <ark_bn254::g2::Config as ark_ec::short_weierstrass::SWCurveConfig>::COEFF_B;
    let mqx = <Config as ark_ec::bn::BnConfig>::TWIST_MUL_BY_Q_X;
    let mqy = <Config as ark_ec::bn::BnConfig>::TWIST_MUL_BY_Q_Y;

    let mut out = String::with_capacity(2048);
    out.push_str("// Generated from arkworks BN254 config — never hand-edit.\n");
    let _ = writeln!(out, "#define JK_ATE_LEN {}u", ate.len() - 1);
    let digits: Vec<String> = ate[..ate.len() - 1]
        .iter()
        .map(|d| format!("{d}"))
        .collect();
    let _ = writeln!(
        out,
        "constant int JK_ATE[JK_ATE_LEN] = {{ {} }};",
        digits.join(", ")
    );
    let _ = writeln!(out, "#define JK_ELL_COEFFS {coeffs}u");
    let _ = writeln!(
        out,
        "constant uint FQ_TWO_INV[FR_LIMBS] = {};",
        limb_array(&fq_mont_limbs(two_inv))
    );
    for (name, value) in [
        ("JK_G2B_C0", g2b.c0),
        ("JK_G2B_C1", g2b.c1),
        ("JK_MQX_C0", mqx.c0),
        ("JK_MQX_C1", mqx.c1),
        ("JK_MQY_C0", mqy.c0),
        ("JK_MQY_C1", mqy.c1),
    ] {
        let _ = writeln!(
            out,
            "constant uint {name}[FR_LIMBS] = {};",
            limb_array(&fq_mont_limbs(value))
        );
    }
    out
}

/// Lay prepared line coefficients out step-major — coefficient `step` of
/// table row `row` at `(step·n_rows + row)·ELL_COEFF_U32S` — so
/// SIMD-adjacent threads (adjacent rows) stream contiguously. Every
/// prepared point must be non-infinity (infinity G2s carry no
/// coefficients; exclude them and their G1 partners before flattening).
pub fn flatten_prepared_coeffs(preps: &[&ArkG2Prepared], out: &mut Vec<u32>) {
    let n_rows = preps.len();
    let steps = ell_coeffs_per_pair();
    for prep in preps {
        assert!(!prep.infinity, "flatten: infinity G2 has no coefficients");
        assert_eq!(prep.ell_coeffs.len(), steps);
    }
    out.clear();
    out.resize(steps * n_rows * ELL_COEFF_U32S, 0);
    if n_rows == 0 {
        return;
    }
    // Each step's rows form one contiguous slice — parallelize over steps
    // (a 2.2 GiB layout write at the 2^27 row count).
    let write_step = |(step, chunk): (usize, &mut [u32])| {
        for (pair, prep) in preps.iter().enumerate() {
            let at = pair * ELL_COEFF_U32S;
            let coeff = &prep.ell_coeffs[step];
            write_fq2(&mut chunk[at..at + 2 * FR_U32_LIMBS], &coeff.0);
            write_fq2(
                &mut chunk[at + 2 * FR_U32_LIMBS..at + 4 * FR_U32_LIMBS],
                &coeff.1,
            );
            write_fq2(
                &mut chunk[at + 4 * FR_U32_LIMBS..at + 6 * FR_U32_LIMBS],
                &coeff.2,
            );
        }
    };
    #[cfg(feature = "parallel")]
    {
        use rayon::prelude::*;
        out.par_chunks_mut(n_rows * ELL_COEFF_U32S)
            .enumerate()
            .for_each(write_step);
    }
    #[cfg(not(feature = "parallel"))]
    out.chunks_mut(n_rows * ELL_COEFF_U32S)
        .enumerate()
        .for_each(write_step);
}

/// One bounded-residency Miller dispatch's coefficient tile (W15): the
/// batch's referenced table rows gathered into a compact step-major table
/// of width `unique.len()`, plus each pair's tile-local row. Identical
/// coefficient values reach the kernel at identical pair positions, so the
/// per-thread partials are bit-equal to a full-table dispatch — only the
/// bytes the device can touch shrink from O(table rows) to O(batch).
/// Buffers recycle across dispatches (the backing must stay address-stable
/// while wrapped — `Vec` heap storage is).
#[derive(Default)]
pub struct MillerTile {
    pub coeffs: Vec<u32>,
    pub local_rows: Vec<u32>,
    unique: Vec<u32>,
}

impl MillerTile {
    /// Gather `row_indices`' rows of `preps` into this tile: sorted-unique
    /// rows, per-pair local remap, and the coefficient gather in
    /// [`flatten_prepared_coeffs`]'s layout at width [`Self::n_rows`].
    pub fn build(&mut self, preps: &[ArkG2Prepared], row_indices: &[u32]) {
        let span = tracing::info_span!("MetalCommit::miller_tile", rows = 0u64);
        let _entered = span.enter();
        self.unique.clear();
        self.unique.extend_from_slice(row_indices);
        self.unique.sort_unstable();
        self.unique.dedup();
        let _ = span.record("rows", self.unique.len() as u64);
        self.local_rows.clear();
        self.local_rows.extend(
            row_indices
                .iter()
                .map(|row| self.unique.partition_point(|&at| at < *row) as u32),
        );
        let steps = ell_coeffs_per_pair();
        for &row in &self.unique {
            let prep = &preps[row as usize];
            assert!(!prep.infinity, "tile: infinity G2 has no coefficients");
            assert_eq!(prep.ell_coeffs.len(), steps);
        }
        self.coeffs.clear();
        self.coeffs
            .resize(steps * self.unique.len() * ELL_COEFF_U32S, 0);
        if self.unique.is_empty() {
            return;
        }
        let write_step = |(step, chunk): (usize, &mut [u32])| {
            for (tile_row, &row) in self.unique.iter().enumerate() {
                let at = tile_row * ELL_COEFF_U32S;
                let coeff = &preps[row as usize].ell_coeffs[step];
                write_fq2(&mut chunk[at..at + 2 * FR_U32_LIMBS], &coeff.0);
                write_fq2(
                    &mut chunk[at + 2 * FR_U32_LIMBS..at + 4 * FR_U32_LIMBS],
                    &coeff.1,
                );
                write_fq2(
                    &mut chunk[at + 4 * FR_U32_LIMBS..at + 6 * FR_U32_LIMBS],
                    &coeff.2,
                );
            }
        };
        let row_u32s = self.unique.len() * ELL_COEFF_U32S;
        #[cfg(feature = "parallel")]
        {
            use rayon::prelude::*;
            self.coeffs
                .par_chunks_mut(row_u32s)
                .enumerate()
                .for_each(write_step);
        }
        #[cfg(not(feature = "parallel"))]
        self.coeffs
            .chunks_mut(row_u32s)
            .enumerate()
            .for_each(write_step);
    }

    /// The tile's table width (unique referenced rows).
    pub fn n_rows(&self) -> usize {
        self.unique.len()
    }
}

/// View affine G1 points as the device `uint` stream (same contract as
/// [`super::g1::bases_as_u32s`]; identity's (0, 0) coordinates ARE the
/// device sentinel, so identities may be included).
pub(super) fn g1_points_as_u32s(points: &[G1Affine]) -> &[u32] {
    // SAFETY: layout pinned by the const asserts in `super::field`; every
    // bit pattern is a valid u32; same lifetime as `points`.
    unsafe {
        std::slice::from_raw_parts(
            points.as_ptr().cast::<u32>(),
            points.len() * G1_AFFINE_U32_STRIDE,
        )
    }
}

/// The multiplicative fold of the per-thread partial Miller values.
pub fn product_of_partials(partials: &[u32]) -> <Bn254 as Pairing>::TargetField {
    partials
        .chunks_exact(FQ12_U32S)
        .fold(Fq12::one(), |acc, limbs| {
            acc * fq12_from_device_limbs(limbs)
        })
}

/// Deterministic projective pairing inputs for the stage-8 multi-pair
/// benches: generator multiples of a splitmix64 scalar stream (the
/// [`super::testing::seeded_frs`] generator), rayon-parallel under
/// `parallel`. Miller cost is data-oblivious, so generator multiples time
/// identically to uniform points.
pub fn seeded_pairing_inputs(seed: u64, n: usize) -> (Vec<ArkG1>, Vec<ArkG2>) {
    use ark_ff::PrimeField;
    let mut state = seed;
    let mut next_u64 = move || {
        state = state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = state;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    };
    let scalars: Vec<(ark_bn254::Fr, ark_bn254::Fr)> = (0..n)
        .map(|_| {
            let mut fr = || {
                let mut bytes = [0u8; 64];
                for chunk in bytes.chunks_exact_mut(8) {
                    chunk.copy_from_slice(&next_u64().to_le_bytes());
                }
                ark_bn254::Fr::from_le_bytes_mod_order(&bytes)
            };
            (fr(), fr())
        })
        .collect();
    let point_pair = |(s1, s2): &(ark_bn254::Fr, ark_bn254::Fr)| {
        (
            ArkG1(G1Affine::generator() * s1),
            ArkG2(G2Affine::generator() * s2),
        )
    };
    #[cfg(feature = "parallel")]
    {
        use rayon::prelude::*;
        scalars.par_iter().map(point_pair).unzip()
    }
    #[cfg(not(feature = "parallel"))]
    scalars.iter().map(point_pair).unzip()
}

/// Uniform `pairs_per_thread` segmentation — the test/bench convenience
/// for [`miller_table_partials`]' ragged segment interface.
pub fn uniform_seg_starts(n_pairs: usize, pairs_per_thread: usize) -> Vec<u32> {
    let n_threads = n_pairs.div_ceil(pairs_per_thread);
    (0..=n_threads)
        .map(|t| (t * pairs_per_thread).min(n_pairs) as u32)
        .collect()
}

/// The kernel's `[[buffer]]`/params contract, shared with the commit slot's
/// in-pipeline dispatch: pair `i` = `points[i]` against table row
/// `row_indices[i]`; thread `t` owns pairs
/// `seg_starts[t]..seg_starts[t + 1]` and writes one partial Miller value.
pub fn miller_table_params(n_threads: usize, n_rows: usize) -> Result<[u32; 2], MetalError> {
    Ok([
        u32::try_from(n_threads).map_err(|_| MetalError::Execution("thread count".into()))?,
        u32::try_from(n_rows).map_err(|_| MetalError::Execution("table rows".into()))?,
    ])
}

/// Dispatch the prepared-coefficient Miller kernel synchronously (the
/// test/bench path; the commit slot encodes the same dispatch inline to
/// overlap its CPU share). Returns the raw partial-f limb buffer (one Fq12
/// per thread).
pub fn miller_table_partials(
    ctx: &MetalContext,
    points: &[G1Affine],
    row_indices: &[u32],
    seg_starts: &[u32],
    coeffs: &[u32],
    n_rows: usize,
) -> Result<Vec<u32>, MetalError> {
    assert_eq!(points.len(), row_indices.len());
    assert_eq!(
        coeffs.len(),
        ell_coeffs_per_pair() * n_rows * ELL_COEFF_U32S
    );
    let n_threads = seg_starts.len() - 1;
    let ps_buf = ctx.wrap_slice(g1_points_as_u32s(points))?;
    let idx_buf = ctx.wrap_slice(row_indices)?;
    let seg_buf = ctx.wrap_slice(seg_starts)?;
    let coeffs_buf = ctx.wrap_slice(coeffs)?;
    let out_buf = ctx.alloc_u32s(n_threads * FQ12_U32S)?;
    ctx.run_once(
        KernelId::MillerTable,
        &miller_table_params(n_threads, n_rows)?,
        &[&ps_buf, &idx_buf, &seg_buf, &coeffs_buf, &out_buf],
        n_threads,
    )?;
    let mut partials = vec![0u32; n_threads * FQ12_U32S];
    out_buf.copy_to_u32s(&mut partials);
    Ok(partials)
}

/// View affine G2 points as the device `uint` stream (identities included —
/// the (0, 0) sentinel skips them on device, as arkworks' filter does).
pub(super) fn g2_points_as_u32s(points: &[G2Affine]) -> &[u32] {
    // SAFETY: layout pinned by the const asserts in `super::field`.
    unsafe {
        std::slice::from_raw_parts(
            points.as_ptr().cast::<u32>(),
            points.len() * G2_AFFINE_U32_STRIDE,
        )
    }
}

/// Dispatch the on-the-fly Miller kernel over affine pairs (one per
/// thread); returns the raw partial-f limb buffer.
pub fn miller_fly_partials(
    ctx: &MetalContext,
    points: &[G1Affine],
    qs: &[G2Affine],
) -> Result<Vec<u32>, MetalError> {
    assert_eq!(points.len(), qs.len());
    let n_pairs = points.len();
    let ps_buf = ctx.wrap_slice(g1_points_as_u32s(points))?;
    let qs_buf = ctx.wrap_slice(g2_points_as_u32s(qs))?;
    let out_buf = ctx.alloc_u32s(n_pairs * FQ12_U32S)?;
    let params = [u32::try_from(n_pairs).map_err(|_| MetalError::Execution("pair count".into()))?];
    ctx.run_once(
        KernelId::MillerFly,
        &params,
        &[&ps_buf, &qs_buf, &out_buf],
        n_pairs,
    )?;
    let mut partials = vec![0u32; n_pairs * FQ12_U32S];
    out_buf.copy_to_u32s(&mut partials);
    Ok(partials)
}

/// Split-ladder toggle for the stage-8 fly path (`JOLT_MILLER_FLY_SPLIT=1`
/// opts in; **default off — measured NO-GO on the M5 Max, W4-fly**). The
/// premise was that `jk_miller_fly`'s ~430 live u32 words (f + G2Hom + q +
/// line + mul temporaries) pay compiler spill traffic on every f touch, so
/// two passes with disjoint state ([`miller_fly_split_partials`]) should
/// win. Measured at 8192 pairs: lines 0.77 + fold 2.79 µs/pair — the
/// isolated passes SUM to the fused wall (3.47), and the two-phase
/// dispatch pays +12.7% on top (+20.5% under the register cap). The fused
/// kernel already overlaps ladder ALU with the f-walk's spill stalls;
/// isolating the passes forfeits that overlap and buys no per-pass rate,
/// because the spill boundary sits far below even a lone Fq12 accumulator
/// (see the T1 fq6-chain rates). Kept for experiments; read per call —
/// the benches A/B it in-process.
pub const ENV_MILLER_FLY_SPLIT: &str = "JOLT_MILLER_FLY_SPLIT";

fn miller_fly_split_enabled() -> bool {
    std::env::var(ENV_MILLER_FLY_SPLIT).is_ok_and(|value| value.trim() == "1")
}

/// log2 of the split scratch block (`JOLT_MILLER_FLY_BLOCK_LOG2`, default
/// 2^15 pairs ≈ 547 MB of line records): bounds transient footprint at
/// production sizes while keeping each pass wide enough to fill the device.
pub const ENV_MILLER_FLY_BLOCK_LOG2: &str = "JOLT_MILLER_FLY_BLOCK_LOG2";
const DEFAULT_MILLER_FLY_BLOCK_LOG2: u32 = 15;

fn miller_fly_block_pairs() -> usize {
    let log2 = std::env::var(ENV_MILLER_FLY_BLOCK_LOG2)
        .ok()
        .and_then(|value| value.trim().parse::<u32>().ok())
        .unwrap_or(DEFAULT_MILLER_FLY_BLOCK_LOG2)
        .min(24);
    1usize << log2
}

/// [`miller_fly_partials`] as the two-pass split ladder (W4-fly): pass 1
/// (`jk_miller_fly_lines`) runs the G2 preparation ladder with no Fq12
/// state and writes P-scaled line records step-major; pass 2
/// (`jk_miller_fly_fold`) replays the ate walk over the records with no
/// ladder state. Blocks of [`miller_fly_block_pairs`] pairs reuse one
/// scratch table inside a single command buffer (barriers order the
/// write→read and read→rewrite hazards). Partials are bit-identical to the
/// fused kernel's — same field ops on the same values in the same order.
pub fn miller_fly_split_partials(
    ctx: &MetalContext,
    points: &[G1Affine],
    qs: &[G2Affine],
) -> Result<Vec<u32>, MetalError> {
    assert_eq!(points.len(), qs.len());
    let n_pairs = points.len();
    if n_pairs == 0 {
        return Ok(Vec::new());
    }
    let block = miller_fly_block_pairs().min(n_pairs);
    let steps = ell_coeffs_per_pair();
    let ps_buf = ctx.wrap_slice(g1_points_as_u32s(points))?;
    let qs_buf = ctx.wrap_slice(g2_points_as_u32s(qs))?;
    let lines_buf = ctx.alloc_u32s(block * steps * ELL_COEFF_U32S)?;
    let flags_buf = ctx.alloc_u32s(block)?;
    let out_buf = ctx.alloc_u32s(n_pairs * FQ12_U32S)?;
    let mut pass = ctx.begin_pass()?;
    let mut base = 0usize;
    while base < n_pairs {
        let n_block = (n_pairs - base).min(block);
        let params = [
            u32::try_from(n_block).map_err(|_| MetalError::Execution("block pairs".into()))?,
            u32::try_from(base).map_err(|_| MetalError::Execution("block base".into()))?,
        ];
        if base != 0 {
            // Previous fold must finish reading the scratch table before
            // this block's lines pass rewrites it.
            pass.buffer_barrier();
        }
        pass.dispatch(
            KernelId::MillerFlyLines,
            &params,
            &[&ps_buf, &qs_buf, &lines_buf, &flags_buf],
            n_block,
        );
        pass.buffer_barrier();
        pass.dispatch(
            KernelId::MillerFlyFold,
            &params,
            &[&lines_buf, &flags_buf, &out_buf],
            n_block,
        );
        base += n_block;
    }
    pass.run()?;
    let mut partials = vec![0u32; n_pairs * FQ12_U32S];
    out_buf.copy_to_u32s(&mut partials);
    Ok(partials)
}

/// The fly-family dispatch the stage-8 hook uses: split ladder unless
/// [`ENV_MILLER_FLY_SPLIT`] disables it.
fn miller_fly_device_partials(
    ctx: &MetalContext,
    points: &[G1Affine],
    qs: &[G2Affine],
) -> Result<Vec<u32>, MetalError> {
    if miller_fly_split_enabled() {
        miller_fly_split_partials(ctx, points, qs)
    } else {
        miller_fly_partials(ctx, points, qs)
    }
}

/// Stage-0 twin of [`miller_fly_partials`]: G2 setup rows remain shared,
/// while `row_indices` selects one for each G1 point. This avoids expanding
/// repeated setup rows or building the prepared-coefficient table.
pub fn miller_fly_indexed_partials(
    ctx: &MetalContext,
    points: &[G1Affine],
    row_indices: &[u32],
    qs: &[G2Affine],
) -> Result<Vec<u32>, MetalError> {
    assert_eq!(points.len(), row_indices.len());
    assert!(
        row_indices.iter().all(|&row| (row as usize) < qs.len()),
        "Miller row index exceeds the G2 table"
    );
    let n_pairs = points.len();
    let ps_buf = ctx.wrap_slice(g1_points_as_u32s(points))?;
    let row_indices_buf = ctx.wrap_slice(row_indices)?;
    let qs_buf = ctx.wrap_slice(g2_points_as_u32s(qs))?;
    let out_buf = ctx.alloc_u32s(n_pairs * FQ12_U32S)?;
    let params = [u32::try_from(n_pairs).map_err(|_| MetalError::Execution("pair count".into()))?];
    ctx.run_once(
        KernelId::MillerFlyIndexed,
        &params,
        &[&ps_buf, &row_indices_buf, &qs_buf, &out_buf],
        n_pairs,
    )?;
    let mut partials = vec![0u32; n_pairs * FQ12_U32S];
    out_buf.copy_to_u32s(&mut partials);
    Ok(partials)
}

/// Per-pair Fq-mul-equivalents fed to [`super::metal_gate`] so the shared
/// `JOLT_METAL_MIN_TERMS` scale keeps meaning "work items": the shift
/// calibrates the default threshold (2^16) to a 2048-pair floor. Below
/// it, per-thread ate-ladder latency dominates (the W5a
/// ladder-latency-floor lesson) while dory's internally parallel CPU
/// multi-pair shrinks linearly. In-pipeline sweep (sha2-chain @2^22,
/// stage-8 wall): hook off → 2.20/2.18 s, ≥4096 pairs → 2.12,
/// **≥2048 → 2.02/2.02**, ≥1024 → 2.11 (the third reduce round loses).
pub(super) const MILLER_FLY_WORK_PER_PAIR_LOG2: usize = 5;

/// Percent of a served multi-pair evaluated on the CPU concurrently with
/// the device dispatch (`JOLT_MILLER_CPU_PCT`, clamped to 90; 0 = pure
/// device). **Default 0 — measured NO-GO on the M5 Max (W3-st8):** the
/// device sustains 2.75-3.5 µs/pair at production reduce-round sizes,
/// while the honest co-run CPU rate is 45-55 µs/pair — wave-1's 13.5
/// µs/pair "fly twin" was a lucky draw of `multi_miller_loop`'s internal
/// 4-pair re-chunking, and even the deterministic prepared-ladder path
/// hits a ~2.7×/18-thread parallel-scaling ceiling on chunky pairing
/// tasks. At 20% the split REGRESSED the 2^17 hook call 375 → ~900 ms.
/// The mechanism (exact-partition Miller split, one final exponentiation)
/// stays for machines where the ratio differs; parity is pinned across
/// shares. Read per call — the hook fires ~100 times per proof, and the
/// benches A/B it in-process.
pub const ENV_MILLER_CPU_PCT: &str = "JOLT_MILLER_CPU_PCT";
const DEFAULT_MILLER_CPU_PCT: usize = 0;

/// CPU shares below this many pairs stay on the device: the rayon fan-out
/// plus per-chunk G2 preparation has nothing to amortize against.
const MILLER_CPU_MIN_PAIRS: usize = 512;

fn miller_cpu_tail(n_pairs: usize) -> usize {
    let pct = std::env::var(ENV_MILLER_CPU_PCT)
        .ok()
        .and_then(|value| value.trim().parse::<usize>().ok())
        .unwrap_or(DEFAULT_MILLER_CPU_PCT)
        .min(90);
    let tail = n_pairs * pct / 100;
    if tail < MILLER_CPU_MIN_PAIRS {
        0
    } else {
        tail
    }
}

/// The CPU share of a split multi-pair: `jolt_dory`'s deterministic
/// chunked prepared-ladder Miller (NOT `Bn254::multi_miller_loop`, whose
/// internal 4-pair re-chunking is nondeterministically 3-4× slower on a
/// saturated rayon pool). Identity filtering matches the device sentinel
/// skip. Empty input is the empty product.
fn cpu_miller_product(ps: &[G1Affine], qs: &[G2Affine]) -> Fq12 {
    if ps.is_empty() {
        return Fq12::one();
    }
    jolt_dory::multi_miller_affine(ps, qs)
}

/// [`product_of_partials`] on rayon chunks — the same value by
/// associativity/commutativity of the Fq12 product, off the caller's
/// critical path at reduce-round sizes (10⁵ sequential Fq12 muls
/// otherwise).
pub fn product_of_partials_par(partials: &[u32]) -> Fq12 {
    #[cfg(feature = "parallel")]
    {
        use rayon::prelude::*;
        partials
            .par_chunks(256 * FQ12_U32S)
            .map(product_of_partials)
            .product()
    }
    #[cfg(not(feature = "parallel"))]
    product_of_partials(partials)
}

