//! Host driver for the device Miller-loop kernels (W6).
//!
//! Two kernel shapes over the `fq12.metal` tower:
//!
//! - [`miller_table_partials`] — the stage-0 tier-2 shape: G1 points against
//!   host-PREPARED G2 line coefficients ([`flatten_prepared_coeffs`] lays
//!   them out step-major), several pairs per thread, one partial Miller
//!   value out per thread.
//! - [`miller_fly_partials`] — the stage-8 reduce-round shape: affine
//!   (G1, G2) pairs with the G2 preparation ladder run inline on the
//!   device, one pair per thread.
//! - [`miller_fly_indexed_partials`] — the stage-0 shape after W3: G1 points
//!   select affine G2 setup rows by index, avoiding the prepared table.
//!
//! Either way the batch Miller value is the exact Fq12 product of the
//! partials ([`product_of_partials`]): a multi-Miller loop over a pair set
//! equals the product of the loops over any partition (the shared squaring
//! ladder distributes — see `jolt_dory::tier2`), so ANY thread partition
//! reproduces `Bn254::multi_miller_loop` exactly, final exponentiation
//! staying on the CPU unchanged.
//!
//! The pairing constants the shaders need (ate digits, twist coefficients,
//! ½) are generated by [`pairing_preamble`] from arkworks' BN254
//! configuration at context construction — no limb value is hand-written,
//! and the structural facts the MSL specializes on (ξ = 9 + u, u² = −1,
//! positive x) are asserted before any pipeline is built.

use ark_bn254::{Bn254, Fq, Fq12, Fq2, Fq6, G1Affine, G1Projective, G2Affine, G2Projective};
use ark_ec::pairing::{MillerLoopOutput, Pairing};
use ark_ec::{AffineRepr, CurveGroup};
use ark_ff::{BigInt, Field, Fp6Config, One};
pub use dory::backends::arkworks::{ArkG1, ArkG2, ArkGT};

