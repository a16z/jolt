fn check<F: Field, T: Copy>(vectors: &[Vector<T>], decode: impl Fn(T) -> F) {
    for &(a, b, product, square, inverse) in vectors {
        let a = decode(a);
        let b = decode(b);
        assert_eq!(a * b, decode(product));
        assert_eq!(a.square(), decode(square));
        assert_eq!(a.inverse(), inverse.map(&decode));
    }
}

